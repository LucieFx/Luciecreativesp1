export function getVideoProjects(): WorkProject[] {
  return VIDEO_PROJECTS;
}

export function getShortFormProjects(): WorkProject[] {
  return VIDEO_PROJECTS.filter((p) => p.category !== "Long Form Videos");
}

export function getLongFormProjects(): WorkProject[] {
  return VIDEO_PROJECTS.filter((p) => p.category === "Long Form Videos");
}

export function getVideoProjectBySlug(slug: string): WorkProject | undefined {
  return VIDEO_PROJECTS.find((p) => p.slug === slug || p.aliases?.includes(slug));
}

export function getAllShortFormReelThumbnails(): { posterSrc: string; title?: string }[] {
  const list: { posterSrc: string; title?: string }[] = [];
  const seen = new Set<string>();

  const add = (posterSrc?: string, title?: string, aspectRatio?: string) => {
    if (posterSrc && (!aspectRatio || aspectRatio === "9/16") && !seen.has(posterSrc)) {
      seen.add(posterSrc);
      list.push({ posterSrc, title });
    }
  };

  const shortProjects = getShortFormProjects();
  for (const p of shortProjects) {
    add(p.posterSrc, p.title, p.aspectRatio);
    if (p.multiVideos) {
      for (const mv of p.multiVideos) {
        add(mv.posterSrc, mv.title, mv.aspectRatio);
      }
    }
  }

  if (Array.isArray(NIRVA_MULTI_VIDEOS)) {
    for (const nv of NIRVA_MULTI_VIDEOS) {
      add(nv.posterSrc, nv.title, nv.aspectRatio);
    }
  }

  return list;
}

